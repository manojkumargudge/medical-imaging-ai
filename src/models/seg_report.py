"""Write docs/results_seg.md from reports/segmentation_metrics.json.

Per-case Dice for val and test with the mean and the range. There are no confidence intervals:
with 6 cases per split a bootstrap interval would say little. An existing output is replaced
only with --overwrite.

Run: python -m src.models.seg_report
"""

from __future__ import annotations

import argparse
import json
from collections.abc import Mapping
from pathlib import Path
from typing import Any

SPLITS = ("val", "test")


def render_markdown(report: Mapping[str, Any]) -> str:
    splits = report["splits"]
    for split in SPLITS:
        if not splits[split]["cases"]:
            raise ValueError(f"no {split} cases")
    lines = [
        "# Segmentation results",
        "",
        f"**{report['notice']}** These numbers describe overlap with the reference masks of one "
        "public dataset. They are not a measure of clinical accuracy.",
        "",
        "Generated by `python -m src.models.seg_report`; do not edit by hand.",
        "",
        f"- Dataset: {report['dataset']}, case-level split (DVC stage `seg_split`).",
        f"- Model: MONAI 3D U-Net, checkpoint epoch {report['checkpoint_epoch']}, the highest val "
        "mean Dice among the saved checkpoints.",
        f"- Metric: {report['metric']}.",
        f"- {len(splits['val']['cases'])} val and {len(splits['test']['cases'])} test cases, so "
        "no confidence intervals are given; the range shows the spread.",
        "",
        "| split | cases | mean Dice | min Dice | max Dice |",
        "|---|---|---|---|---|",
    ]
    for split in SPLITS:
        dice = [case["dice"] for case in splits[split]["cases"]]
        lines.append(
            f"| {split} | {len(dice)} | {splits[split]['mean_dice']:.4f} "
            f"| {min(dice):.4f} | {max(dice):.4f} |"
        )
    for split in SPLITS:
        lines += ["", f"## {split} cases", "", "| case | Dice |", "|---|---|"]
        lines += [f"| {case['case']} | {case['dice']:.4f} |" for case in splits[split]["cases"]]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--metrics", type=Path, default=Path("reports/segmentation_metrics.json"))
    parser.add_argument("--results", type=Path, default=Path("docs/results_seg.md"))
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()
    if args.results.exists() and not args.overwrite:
        raise FileExistsError(f"{args.results} exists; pass --overwrite to replace it")
    text = render_markdown(json.loads(args.metrics.read_text(encoding="utf-8")))
    args.results.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.results}")


if __name__ == "__main__":
    main()
